//! Generated reference pages of the documentation site (`docs/src/reference/`).
//!
//! - `api.md` from `openapi/openapi.json` (the locked, template-free document);
//! - `errors.md` from `crates/inkpdf/src/error.rs` (codes, HTTP statuses, titles);
//! - `packages.md` from `packages/lock.toml` and the vendored archives.
//!
//! The same lock file also generates `packages.md` of the plugin's `write-template` skill
//! (`plugins/inkpdf/skills/write-template/`).
//!
//! `check` also verifies that every `INKPDF_*` variable read by the service is documented in the
//! hand-written `configuration.md` and in the complete Compose example of `deployment.md`,
//! checks the plugin files (see `plugin.rs`), and that nothing refers to the example templates
//! removed by feature 005.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow, bail};
use serde_json::Value;

use crate::lock::{self, Entry, Lock, Role};
use crate::plugin;

/// First line of every generated page.
pub const GENERATED: &str = "<!-- generated by `cargo xtask docs generate`; do not edit -->";

/// Bundled packages reference of the `write-template` skill, relative to the repository root.
pub const SKILL_PACKAGES: &str = "plugins/inkpdf/skills/write-template/packages.md";

struct Page {
    path: PathBuf,
    content: String,
}

fn pages(root: &Path) -> Result<Vec<Page>> {
    let reference = root.join("docs/src/reference");
    let openapi: Value = serde_json::from_slice(
        &fs::read(root.join("openapi/openapi.json")).context("reading openapi/openapi.json")?,
    )?;
    let errors = fs::read_to_string(root.join("crates/inkpdf/src/error.rs"))?;
    let packages = bundled_packages(root)?;
    Ok(vec![
        Page {
            path: reference.join("api.md"),
            content: api_md(&openapi),
        },
        Page {
            path: reference.join("errors.md"),
            content: errors_md(&errors)?,
        },
        Page {
            path: reference.join("packages.md"),
            content: packages_md(&packages),
        },
        Page {
            path: root.join(SKILL_PACKAGES),
            content: skill_packages_md(&packages),
        },
    ])
}

/// Generated pages whose file is missing or differs, relative to `root`.
fn stale_pages(root: &Path, pages: &[Page]) -> Vec<String> {
    pages
        .iter()
        .filter(|page| {
            fs::read_to_string(&page.path).ok().as_deref() != Some(page.content.as_str())
        })
        .map(|page| {
            page.path
                .strip_prefix(root)
                .unwrap_or(&page.path)
                .display()
                .to_string()
        })
        .collect()
}

pub fn generate(root: &Path) -> Result<()> {
    for page in pages(root)? {
        fs::create_dir_all(page.path.parent().unwrap())?;
        fs::write(&page.path, &page.content)?;
        println!(
            "wrote {}",
            page.path.strip_prefix(root).unwrap_or(&page.path).display()
        );
    }
    Ok(())
}

pub fn check(root: &Path) -> Result<()> {
    let stale = stale_pages(root, &pages(root)?);
    let config = fs::read_to_string(root.join("crates/inkpdf/src/config.rs"))?;
    // Every variable read by the service appears in the configuration reference and in the
    // complete Docker Compose example.
    let mut missing = Vec::new();
    for page in ["reference/configuration.md", "operations/deployment.md"] {
        let text = fs::read_to_string(root.join("docs/src").join(page)).unwrap_or_default();
        for var in config_variables(&config) {
            if !text.contains(var.as_str()) {
                missing.push(format!("{var} (docs/src/{page})"));
            }
        }
    }

    if !stale.is_empty() {
        eprintln!(
            "out of date (run `cargo xtask docs generate`): {}",
            stale.join(", ")
        );
    }
    if !missing.is_empty() {
        eprintln!(
            "configuration variables not documented: {}",
            missing.join(", ")
        );
    }
    let plugin = plugin::problems(root)?;
    for problem in &plugin {
        eprintln!("plugin: {problem}");
    }
    let removed = removed_template_references(root)?;
    for reference in &removed {
        eprintln!("reference to a removed example template: {reference}");
    }
    if stale.is_empty() && missing.is_empty() && plugin.is_empty() && removed.is_empty() {
        println!("generated documentation is up to date; plugin files are valid");
        Ok(())
    } else {
        bail!("documentation check failed")
    }
}

/// Names of the example templates removed by feature 005 (`demo` replaces them), including the
/// PascalCase form that generated clients use (`renderProgressInvoice`, `PackagesDemoData`).
const REMOVED_TEMPLATES: [&str; 5] = [
    "progress-invoice",
    "packages-demo",
    "examples/templates/sample",
    "ProgressInvoice",
    "PackagesDemo",
];

/// Folders and files, relative to the repository root, that must not refer to a removed example
/// template.
const REFERENCE_SCOPE: [&str; 5] = [
    "docs/src",
    "examples",
    "plugins",
    "README.md",
    "compose.yaml",
];

/// Every `path:line: name` where a removed example template is named in [`REFERENCE_SCOPE`].
/// Files that are not UTF-8 text are skipped.
fn removed_template_references(root: &Path) -> Result<Vec<String>> {
    fn walk(path: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
        if path.is_dir() {
            let mut entries = fs::read_dir(path)
                .with_context(|| format!("reading {}", path.display()))?
                .map(|entry| entry.map(|e| e.path()))
                .collect::<std::io::Result<Vec<_>>>()?;
            entries.sort();
            for entry in entries {
                walk(&entry, out)?;
            }
        } else if path.is_file() {
            out.push(path.to_path_buf());
        }
        Ok(())
    }

    let mut files = Vec::new();
    for scope in REFERENCE_SCOPE {
        walk(&root.join(scope), &mut files)?;
    }
    let mut found = Vec::new();
    for file in files {
        let Ok(text) = fs::read_to_string(&file) else {
            continue;
        };
        let shown = file
            .strip_prefix(root)
            .unwrap_or(&file)
            .display()
            .to_string();
        for (number, line) in text.lines().enumerate() {
            for name in REMOVED_TEMPLATES {
                if line.contains(name) {
                    found.push(format!("{shown}:{}: {name}", number + 1));
                }
            }
        }
    }
    Ok(found)
}

/// `INKPDF_*` variables read in `config.rs`.
fn config_variables(source: &str) -> BTreeSet<String> {
    source
        .split('"')
        .filter(|chunk| {
            chunk.starts_with("INKPDF_")
                && chunk.chars().all(|c| c.is_ascii_uppercase() || c == '_')
        })
        .map(str::to_owned)
        .collect()
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// Reference of the generic HTTP API.
fn api_md(openapi: &Value) -> String {
    let mut out = format!(
        "{GENERATED}\n\n# HTTP API\n\n\
This page lists the **generic** routes of inkpdf, generated from the locked OpenAPI document\n\
(`openapi/openapi.json`).\n\n\
A running instance publishes a richer document: `GET /openapi.json` adds one typed render\n\
operation per template currently loaded (`POST /templates/<id>/render`, whose request body is\n\
that template's own schema), and `GET /docs` renders it interactively. Point an OpenAPI\n\
generator at a running instance to get a client typed per template.\n\n\
Errors use RFC 9457 `application/problem+json` bodies; see [Error codes](errors.md).\n"
    );
    let Some(paths) = openapi["paths"].as_object() else {
        return out;
    };
    for (path, item) in paths {
        let Some(methods) = item.as_object() else {
            continue;
        };
        for (method, op) in methods {
            out.push_str(&format!("\n## `{} {path}`\n\n", method.to_uppercase()));
            if let Some(summary) = op["summary"].as_str() {
                out.push_str(&format!("**{}**\n\n", summary.trim()));
            }
            if let Some(description) = op["description"].as_str() {
                out.push_str(&format!("{}\n\n", description.trim()));
            }
            if let Some(params) = op["parameters"].as_array().filter(|p| !p.is_empty()) {
                out.push_str("| Parameter | In | Required | Description |\n|---|---|---|---|\n");
                for p in params {
                    out.push_str(&format!(
                        "| `{}` | {} | {} | {} |\n",
                        p["name"].as_str().unwrap_or(""),
                        p["in"].as_str().unwrap_or(""),
                        if p["required"].as_bool().unwrap_or(false) {
                            "yes"
                        } else {
                            "no"
                        },
                        cell(p["description"].as_str().unwrap_or("")),
                    ));
                }
                out.push('\n');
            }
            if let Some(content) = op["requestBody"]["content"].as_object() {
                for (media, body) in content {
                    let schema = body["schema"]["$ref"]
                        .as_str()
                        .and_then(|r| r.rsplit('/').next())
                        .map(|name| format!("`{name}`"))
                        .unwrap_or_else(|| "see the OpenAPI document".into());
                    out.push_str(&format!("Request body: `{media}`, schema {schema}.\n\n"));
                }
            }
            if let Some(responses) = op["responses"].as_object() {
                out.push_str("| Status | Description |\n|---|---|\n");
                for (status, response) in responses {
                    let description = response["description"]
                        .as_str()
                        .map(str::to_owned)
                        .or_else(|| {
                            response["$ref"].as_str().map(|r| {
                                format!("Problem ({})", r.rsplit('/').next().unwrap_or(""))
                            })
                        })
                        .unwrap_or_default();
                    out.push_str(&format!("| {status} | {} |\n", cell(&description)));
                }
            }
        }
    }
    out
}

/// Parses the `Self::Variant => value` arms of the `fn <name>` match in `error.rs`.
fn match_arms(source: &str, function: &str) -> Result<Vec<(Vec<String>, String)>> {
    let start = source
        .find(&format!("fn {function}("))
        .ok_or_else(|| anyhow!("fn {function} not found in error.rs"))?;
    let body = &source[start..];
    let end = body.find("\n    }\n").unwrap_or(body.len());
    let mut arms = Vec::new();
    for line in body[..end].lines() {
        let Some((left, right)) = line.trim().split_once("=>") else {
            continue;
        };
        let variants: Vec<String> = left
            .split('|')
            .filter_map(|v| {
                v.trim()
                    .strip_prefix("Self::")
                    .map(|v| v.split(['{', ' ']).next().unwrap().to_owned())
            })
            .collect();
        if !variants.is_empty() {
            arms.push((variants, right.trim().trim_end_matches(',').to_owned()));
        }
    }
    Ok(arms)
}

fn http_status(name: &str) -> Option<u16> {
    Some(match name.strip_prefix("StatusCode::")? {
        "BAD_REQUEST" => 400,
        "NOT_FOUND" => 404,
        "CONFLICT" => 409,
        "PAYLOAD_TOO_LARGE" => 413,
        "UNSUPPORTED_MEDIA_TYPE" => 415,
        "UNPROCESSABLE_ENTITY" => 422,
        "INTERNAL_SERVER_ERROR" => 500,
        "SERVICE_UNAVAILABLE" => 503,
        "GATEWAY_TIMEOUT" => 504,
        _ => return None,
    })
}

/// Reference of the error codes.
fn errors_md(error_rs: &str) -> Result<String> {
    let lookup = |function: &str| -> Result<BTreeMap<String, String>> {
        Ok(match_arms(error_rs, function)?
            .into_iter()
            .flat_map(|(variants, value)| variants.into_iter().map(move |v| (v, value.clone())))
            .collect())
    };
    let codes = lookup("as_str")?;
    let statuses = lookup("status")?;
    let titles = lookup("title")?;

    let mut rows: Vec<(u16, String, String)> = Vec::new();
    for (variant, code) in &codes {
        let status = statuses
            .get(variant)
            .and_then(|s| http_status(s))
            .ok_or_else(|| anyhow!("no known HTTP status for {variant}"))?;
        let title = titles.get(variant).cloned().unwrap_or_default();
        rows.push((
            status,
            code.trim_matches('"').to_owned(),
            title.trim_matches('"').to_owned(),
        ));
    }
    rows.sort();
    let mut out = format!(
        "{GENERATED}\n\n# Error codes\n\n\
Every error response is an RFC 9457 `application/problem+json` body with a machine-readable\n\
`code`. Validation errors add `violations[]` (JSON Pointers into the request body and the\n\
schema); rendering errors add `diagnostics[]` (message, file, line, column, hints). Files\n\
inside a bundled package are shown as `@preview/<name>:<version>/<path>`.\n\n\
| HTTP status | `code` | Title |\n|---|---|---|\n"
    );
    for (status, code, title) in rows {
        out.push_str(&format!("| {status} | `{code}` | {title} |\n"));
    }
    Ok(out)
}

/// A bundled package, with the description from its manifest and whether it ships a WASM
/// plugin.
struct Bundled {
    entry: Entry,
    description: String,
    wasm: bool,
}

/// Every package of the lock file, sorted by name and version, read from its vendored archive.
fn bundled_packages(root: &Path) -> Result<Vec<Bundled>> {
    let mut entries = Lock::read(root)?.package;
    entries.sort_by_key(Entry::key);
    entries
        .into_iter()
        .map(|entry| {
            let archive = fs::read(Lock::vendor(root).join(entry.archive_name()))
                .with_context(|| format!("archive of {} {}", entry.name, entry.version))?;
            let files = lock::archive_files(&archive)?;
            let manifest = lock::manifest(&files)?;
            let description = manifest
                .get("description")
                .and_then(|d| d.as_str())
                .unwrap_or("")
                .trim()
                .to_owned();
            let wasm = files.keys().any(|path| path.ends_with(".wasm"));
            Ok(Bundled {
                entry,
                description,
                wasm,
            })
        })
        .collect()
}

/// Reference of the bundled Typst packages.
fn packages_md(packages: &[Bundled]) -> String {
    let mut out = format!(
        "{GENERATED}\n\n# Bundled packages\n\n\
These [Typst Universe](https://typst.app/universe) packages are embedded in the inkpdf binary;\n\
nothing is ever downloaded. Import them **by name only** — the service uses the installed\n\
version (see [Bundled packages](../concepts/packages.md)). A running instance lists them at\n\
`GET /packages`.\n\n\
## Available packages\n\n\
| Import | Description | Version | License | WASM |\n|---|---|---|---|---|\n"
    );
    for package in packages.iter().filter(|p| p.entry.role == Role::Selected) {
        out.push_str(&format!(
            "| `@preview/{}` | {} | {} | {} | {} |\n",
            package.entry.name,
            cell(&package.description),
            package.entry.version,
            package.entry.license,
            if package.wasm { "yes" } else { "" },
        ));
    }
    out.push_str(
        "\n**WASM**: the package contains a compiled plugin. It runs inside the engine without\n\
network or file access, but a very long plugin call cannot be interrupted before it ends;\n\
see [Limits and performance](../operations/limits.md).\n\n\
## Licenses\n\n\
Every bundled package, including internal dependencies that templates cannot import. Each\n\
package ships with its license text inside the binary.\n\n\
| Package | Version | Role | License |\n|---|---|---|---|\n",
    );
    for Bundled { entry, .. } in packages {
        out.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            entry.name,
            entry.version,
            match entry.role {
                Role::Selected => "available to templates",
                Role::Dependency => "dependency",
            },
            entry.license,
        ));
    }
    out
}

/// Bundled packages reference of the `write-template` skill: what an assistant needs to pick a
/// package and import it, without the documentation site.
fn skill_packages_md(packages: &[Bundled]) -> String {
    let mut out = format!(
        "{GENERATED}\n\n# Bundled packages\n\n\
The Typst packages an inkpdf template can import. They are built into the inkpdf server:\n\
nothing is downloaded at render time, and no other package is available.\n\n\
- Import a package by name only, exactly as in the table. Writing a version\n  \
(`@preview/<name>:<version>`) or importing a package that is not listed makes the template\n  \
invalid; the server uses the version shown here.\n\
- Write the name as a literal string: `\"@preview/\" + name` is not supported. `#include`\n  \
follows the same rules.\n\
- A package only reads its own files: load images and data in the template, and pass them\n  \
as arguments.\n\
- **WASM**: the package runs a compiled plugin that cannot be interrupted. Keep its input\n  \
small (a code to encode, not a whole document).\n\n\
This list matches the inkpdf release of this plugin. A running server lists its own packages\n\
at `GET /packages`.\n\n\
| Import | Version | Purpose | WASM |\n|---|---|---|---|\n"
    );
    for package in packages.iter().filter(|p| p.entry.role == Role::Selected) {
        out.push_str(&format!(
            "| `#import \"@preview/{}\"` | {} | {} | {} |\n",
            package.entry.name,
            package.entry.version,
            cell(&package.description),
            if package.wasm { "yes" } else { "" },
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn api_page_lists_every_operation() {
        let openapi = json!({
            "paths": {
                "/a": { "get": { "summary": "A", "responses": { "200": { "description": "ok" } } } },
                "/b/{id}": { "post": {
                    "parameters": [{ "name": "id", "in": "path", "required": true, "description": "Id" }],
                    "requestBody": { "content": { "application/json": { "schema": { "$ref": "#/components/schemas/Body" } } } },
                    "responses": { "404": { "$ref": "#/components/responses/Problem" } }
                } }
            }
        });
        let page = api_md(&openapi);
        assert!(page.starts_with(GENERATED));
        assert!(page.contains("## `GET /a`"));
        assert!(page.contains("## `POST /b/{id}`"));
        assert!(page.contains("| `id` | path | yes | Id |"));
        assert!(page.contains("schema `Body`"));
        assert!(page.contains("| 404 | Problem (Problem) |"));
    }

    #[test]
    fn error_page_matches_the_service_source() {
        let source =
            fs::read_to_string(crate::repo_root().join("crates/inkpdf/src/error.rs")).unwrap();
        let page = errors_md(&source).unwrap();
        for (status, code) in [
            (404, "template-not-found"),
            (400, "invalid-parameter"),
            (422, "validation-failed"),
            (504, "render-timeout"),
        ] {
            assert!(
                page.contains(&format!("| {status} | `{code}` |")),
                "{code}\n{page}"
            );
        }
    }

    #[test]
    fn skill_packages_page_lists_every_importable_package_only() {
        let page = skill_packages_md(&bundled_packages(&crate::repo_root()).unwrap());
        assert!(page.starts_with(GENERATED));
        let lock = Lock::read(&crate::repo_root()).unwrap();
        // A dependency may share its name with a selected package (another version): only the
        // selected version is offered.
        for entry in &lock.package {
            let row = format!(
                "`#import \"@preview/{}\"` | {} |",
                entry.name, entry.version
            );
            assert_eq!(
                page.contains(&row),
                entry.role == Role::Selected,
                "{} {}\n{page}",
                entry.name,
                entry.version
            );
        }
    }

    #[test]
    fn stale_pages_are_the_missing_and_changed_ones() {
        let root = std::env::temp_dir().join(format!("inkpdf-xtask-stale-{}", std::process::id()));
        fs::create_dir_all(&root).unwrap();
        fs::write(root.join("same.md"), "same").unwrap();
        fs::write(root.join("changed.md"), "old").unwrap();
        let page = |name: &str, content: &str| Page {
            path: root.join(name),
            content: content.to_owned(),
        };
        let stale = stale_pages(
            &root,
            &[
                page("same.md", "same"),
                page("changed.md", "new"),
                page("missing.md", "new"),
            ],
        );
        fs::remove_dir_all(&root).unwrap();
        assert_eq!(stale, ["changed.md", "missing.md"]);
    }

    #[test]
    fn packages_page_lists_selected_imports_and_all_licenses() {
        let page = packages_md(&bundled_packages(&crate::repo_root()).unwrap());
        let lock = Lock::read(&crate::repo_root()).unwrap();
        for entry in &lock.package {
            if entry.role == Role::Selected {
                assert!(
                    page.contains(&format!("`@preview/{}`", entry.name)),
                    "{}",
                    entry.name
                );
            }
            assert!(
                page.contains(&format!("| {} | {} |", entry.name, entry.version)),
                "{}",
                entry.name
            );
        }
    }

    #[test]
    fn removed_templates_are_found_in_scope_only() {
        let root =
            std::env::temp_dir().join(format!("inkpdf-xtask-removed-{}", std::process::id()));
        let write = |path: &str, content: &[u8]| {
            let path = root.join(path);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, content).unwrap();
        };
        write(
            "docs/src/guide.md",
            b"Render `demo`.\nThen `progress-invoice`.\n",
        );
        write(
            "examples/bruno/a.bru",
            b"url: /templates/packages-demo/render\n",
        );
        write(
            "plugins/skill.md",
            b"See examples/templates/sample/main.typ\n",
        );
        write("README.md", b"Only demo here.\n");
        write("compose.yaml", b"# packages-demo\n");
        write("examples/logo.png", &[0xff, 0xfe, 0x00]);
        write(
            "crates/inkpdf/tests/fixtures/templates/packages-demo/main.typ",
            b"packages-demo\n",
        );
        let found = removed_template_references(&root);
        fs::remove_dir_all(&root).unwrap();
        assert_eq!(
            found.unwrap(),
            [
                "docs/src/guide.md:2: progress-invoice",
                "examples/bruno/a.bru:1: packages-demo",
                "plugins/skill.md:1: examples/templates/sample",
                "compose.yaml:1: packages-demo",
            ]
        );
    }

    #[test]
    fn the_repository_has_no_reference_to_removed_templates() {
        let found = removed_template_references(&crate::repo_root()).unwrap();
        assert!(found.is_empty(), "{found:#?}");
    }

    #[test]
    fn configuration_variables_are_extracted() {
        let vars =
            config_variables(r#"var("INKPDF_LISTEN") … var("INKPDF_DEFAULT_AUTHOR") "not_me""#);
        assert_eq!(
            vars.into_iter().collect::<Vec<_>>(),
            ["INKPDF_DEFAULT_AUTHOR", "INKPDF_LISTEN"]
        );
    }
}
